class LocalMemberUpgradeTests {
 @Test void preservesExistingMembersAndAddsActiveDefaultAndUniqueSlackLink() throws Exception {
  // 기존 H2 데이터는 유지하면서 활성 기본값과 Slack ID 유니크를 적용한다.
  try(var c=DriverManager.getConnection("jdbc:h2:mem:member-upgrade-"+UUID.randomUUID(),"sa","");var s=c.createStatement()) {
   s.execute("CREATE TABLE members(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,family_name varchar(80),given_name varchar(80),team varchar(80),slack_user_id varchar(80))");
   s.execute("INSERT INTO members(family_name,given_name,team,slack_user_id) VALUES ('김','민수','백엔드팀','UOLD')");
   var script=new ClassPathResource("db/local/member-management-upgrade.sql");
   ScriptUtils.executeSqlScript(c,script);ScriptUtils.executeSqlScript(c,script);
   try(var r=s.executeQuery("SELECT active FROM members WHERE slack_user_id='UOLD'")){assertThat(r.next()).isTrue();assertThat(r.getBoolean(1)).isTrue();}
   assertThatThrownBy(()->s.execute("INSERT INTO members(slack_user_id) VALUES ('UOLD')")).isInstanceOf(SQLException.class);
  }
 }
}
