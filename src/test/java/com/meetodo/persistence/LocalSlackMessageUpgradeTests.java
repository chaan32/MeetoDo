package com.meetodo.persistence;

import com.meetodo.meeting.Meeting;
import com.meetodo.slack.SlackMessageReference;
import java.sql.Connection;
import java.sql.DriverManager;
import java.util.UUID;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.Test;
import static org.assertj.core.api.Assertions.assertThat;

class LocalSlackMessageUpgradeTests {
    // 검증: local SQL 초기화 후 ddl-auto=update로 기존 H2 메시지 행을 보존하며 CHANNEL/SENT 기본값을 채운다.
    @Test void existingH2ChannelReferenceGetsNewDefaultsDuringSchemaUpdate() throws Exception {
        String url = legacyDatabase();
        updateSchema(url);
        try (var connection = connect(url); var statement = connection.createStatement();
             var row = statement.executeQuery("SELECT channel_id, message_ts, message_type, delivery_status FROM slack_message_references")) {
            assertThat(row.next()).isTrue();
            assertThat(row.getString("channel_id")).isEqualTo("C123ABC");
            assertThat(row.getString("message_ts")).isEqualTo("1.000001");
            assertThat(row.getString("message_type")).isEqualTo("CHANNEL");
            assertThat(row.getString("delivery_status")).isEqualTo("SENT");
        }
    }

    // 검증: 기존 H2의 NOT NULL 위치 제약도 완화해 대화 열기 실패 DM을 저장할 수 있다.
    @Test void existingH2LocationColumnsBecomeNullableForFailedDm() throws Exception {
        String url = legacyDatabase();
        updateSchema(url);
        try (var connection = connect(url); var statement = connection.createStatement()) {
            assertThat(statement.executeUpdate("INSERT INTO slack_message_references(task_ids, message_type, target_slack_user_id, delivery_status, error_code) VALUES ('[7]', 'DM', 'U123ABC', 'FAILED', 'missing_scope')")).isEqualTo(1);
        }
    }

    @Test void upgradeScriptCanRunAgainWithoutChangingMessageLocation() throws Exception {
        // local 재시작 때 SQL을 반복 실행해도 기존 메시지와 상태는 보존된다.
        String url = legacyDatabase();
        updateSchema(url); updateSchema(url);
        try (var connection = connect(url); var statement = connection.createStatement();
             var row = statement.executeQuery("SELECT count(*) FROM slack_message_references WHERE channel_id='C123ABC' AND message_type='CHANNEL' AND delivery_status='SENT'")) {
            row.next(); assertThat(row.getInt(1)).isEqualTo(1);
        }
    }
    @Test void freshDatabaseStillStartsWithoutLegacyMessageTable() throws Exception {
        // 새 개발 DB는 보정 SQL이 기존 테이블 부재를 건너뛰고 Hibernate로 정상 생성한다.
        String url = "jdbc:h2:mem:slack-fresh-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        updateSchema(url);
        try (var connection = connect(url); var statement = connection.createStatement();
             var row = statement.executeQuery("SELECT count(*) FROM slack_message_references")) {
            row.next(); assertThat(row.getInt(1)).isZero();
        }
    }

    private String legacyDatabase() throws Exception {
        String url = "jdbc:h2:mem:slack-upgrade-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        try (var connection = connect(url); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE slack_message_references (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, channel_id varchar(80) NOT NULL, message_ts varchar(80) NOT NULL, meeting_id bigint, digest_date date, task_ids text NOT NULL, CONSTRAINT uk_slack_message_channel_ts UNIQUE(channel_id, message_ts))");
            statement.executeUpdate("INSERT INTO slack_message_references(channel_id, message_ts, task_ids) VALUES ('C123ABC', '1.000001', '[1,2]')");
        }
        return url;
    }

    private void updateSchema(String url) throws Exception {
        try (var connection = connect(url)) {
            org.springframework.jdbc.datasource.init.ScriptUtils.executeSqlScript(connection,
                    new org.springframework.core.io.ClassPathResource("db/local/slack-message-dm-upgrade.sql"));
            org.springframework.jdbc.datasource.init.ScriptUtils.executeSqlScript(connection,
                    new org.springframework.core.io.ClassPathResource("db/local/reassignment-messages-upgrade.sql"));
        }
        var registry = new StandardServiceRegistryBuilder()
                .applySetting("hibernate.connection.driver_class", "org.h2.Driver")
                .applySetting("hibernate.connection.url", url)
                .applySetting("hibernate.connection.username", "sa")
                .applySetting("hibernate.connection.password", "")
                .applySetting("hibernate.physical_naming_strategy", "org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy")
                .applySetting("hibernate.hbm2ddl.auto", "update")
                .applySetting("hibernate.hbm2ddl.halt_on_error", true)
                .build();
        try (var ignored = new MetadataSources(registry).addAnnotatedClass(Meeting.class)
                .addAnnotatedClass(SlackMessageReference.class).buildMetadata().buildSessionFactory()) {
            // SessionFactory 생성 시 local과 같은 Hibernate update가 실행된다.
        } finally {
            StandardServiceRegistryBuilder.destroy(registry);
        }
    }

    private Connection connect(String url) throws Exception {
        return DriverManager.getConnection(url, "sa", "");
    }
}
