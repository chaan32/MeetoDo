CREATE TABLE slack_message_references (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id varchar(80) NOT NULL,
    message_ts varchar(80) NOT NULL,
    meeting_id bigint REFERENCES meetings(id),
    digest_date date,
    task_ids text NOT NULL,
    CONSTRAINT uk_slack_message_channel_ts UNIQUE (channel_id, message_ts)
);
