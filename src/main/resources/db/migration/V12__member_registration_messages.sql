CREATE TABLE member_registration_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES member_registration_requests(id),
    admin_slack_user_id varchar(80) NOT NULL,
    channel_id varchar(80),
    message_ts varchar(80),
    status varchar(20) NOT NULL,
    error_code varchar(80),
    CONSTRAINT uk_registration_message_admin UNIQUE (request_id, admin_slack_user_id)
);
