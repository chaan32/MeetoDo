CREATE TABLE member_registration_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slack_user_id varchar(80) NOT NULL,
    pending_slack_user_id varchar(80),
    family_name varchar(80) NOT NULL,
    given_name varchar(80) NOT NULL,
    team varchar(80) NOT NULL,
    status varchar(20) NOT NULL,
    processed_by_slack_user_id varchar(80),
    rejection_reason varchar(300),
    member_id bigint REFERENCES members(id),
    duplicate_name boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    processed_at timestamp with time zone,
    CONSTRAINT uk_registration_pending_user UNIQUE (pending_slack_user_id),
    CONSTRAINT ck_registration_state CHECK (
        (status = 'PENDING' AND pending_slack_user_id = slack_user_id AND pending_slack_user_id IS NOT NULL AND processed_at IS NULL)
        OR (status IN ('APPROVED','REJECTED') AND pending_slack_user_id IS NULL AND processed_at IS NOT NULL)
    )
);
CREATE TABLE member_registration_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES member_registration_requests(id),
    type varchar(20) NOT NULL,
    by_slack_user_id varchar(80) NOT NULL,
    before_form text,
    after_form text,
    at timestamp with time zone NOT NULL
);
