CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_name varchar(80) NOT NULL,
    given_name varchar(80) NOT NULL,
    team varchar(80) NOT NULL,
    slack_user_id varchar(80)
);

CREATE TABLE meetings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_text varchar(20000) NOT NULL,
    content_hash varchar(64) NOT NULL,
    source varchar(30) NOT NULL,
    status varchar(20) NOT NULL,
    summary varchar(4000),
    duplicate_of_meeting_id bigint REFERENCES meetings(id),
    started_at timestamp with time zone,
    completed_at timestamp with time zone,
    processing_time_ms bigint,
    llm_call_count integer NOT NULL,
    tool_call_count integer NOT NULL,
    validation_failure_count integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    notification_status varchar(20),
    notification_type varchar(20),
    notification_error_code varchar(40),
    notified_at timestamp with time zone,
    CONSTRAINT uk_meetings_content_hash UNIQUE (content_hash)
);

CREATE TABLE tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    assignee_id bigint REFERENCES members(id),
    unresolved_assignee text,
    due_date date,
    status varchar(20) NOT NULL,
    meeting_id bigint REFERENCES meetings(id),
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE tool_call_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id bigint NOT NULL REFERENCES meetings(id),
    tool_name varchar(100) NOT NULL,
    arguments varchar(4000),
    result varchar(4000),
    success boolean NOT NULL,
    error_code varchar(100),
    error_message varchar(500),
    latency_ms bigint NOT NULL,
    call_order integer NOT NULL,
    created_at timestamp with time zone NOT NULL
);
CREATE INDEX idx_tool_call_logs_meeting_order ON tool_call_logs(meeting_id, call_order);

CREATE TABLE task_mentions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id),
    meeting_id bigint NOT NULL REFERENCES meetings(id),
    mentioned_at timestamp with time zone NOT NULL,
    CONSTRAINT uk_task_mentions_task_meeting UNIQUE (task_id, meeting_id)
);

CREATE TABLE daily_digests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    digest_date date NOT NULL,
    status varchar(20) NOT NULL,
    sent_at timestamp with time zone,
    overdue_count bigint NOT NULL,
    today_count bigint NOT NULL,
    upcoming_count bigint NOT NULL,
    no_due_date_count bigint NOT NULL,
    error_code varchar(40),
    CONSTRAINT uk_daily_digests_date UNIQUE (digest_date)
);
